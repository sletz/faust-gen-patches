#!/usr/bin/env python3
"""Make a gen~ export deterministic for the reference renderer.

Every `noise()` call site of ref/export/<model>.cpp, numbered in file order
(k = 0, 1, ...), becomes `__gen_noise(k)`, which ref/gen_ref.cpp serves from a
noise stream given on the command line instead of genlib's xoshiro256+ seeded
by the clock. The start of the sample loop gets `__gen_tick();` so the renderer
knows the frame. A `Buffer` the GenExpr reads but the export does not declare
(Max 9.2.1 leaves `Buffer buf_taps;` of delays-delays out: `buf_taps.dim`,
`buf_taps.read(i, ch)` on an undeclared name) gets a declaration
`static GenRefBuffer buf_taps("buf_taps");`, a genlib DataInterface<float> that
ref/gen_ref.cpp fills from `--buffer buf_taps=FILE` (empty: genlib's unbound
Buffer, dim 1, channels 1, one 0). Nothing else of the exported code is touched.

    scripts/patch_export.py ref/export/bernoulli_gate.cpp build/ref/bernoulli_gate.cpp
"""
import re, sys

src, dst = sys.argv[1], sys.argv[2]
code = open(src).read()
k = 0
def site(m):
    global k
    s = f"__gen_noise({k})"
    k += 1
    return s
code = re.sub(r"(?<![A-Za-z0-9_])noise\(\)", site, code)
loop = "while ((__n--)) {"
assert code.count(loop) == 1, f"{src}: {code.count(loop)} sample loops"
code = code.replace(loop, loop + " __gen_tick();")
# Buffers read but not declared by the export
bufs = sorted({a for a, b in re.findall(r"int (\w+)_dim = (\w+)\.dim;", code)
               if a == b and not re.search(r"\b(Data|Buffer|DataLocal)\s+" + re.escape(a) + r"\s*;", code)})
if bufs:
    state = "typedef struct State {"
    assert code.count(state) == 1, f"{src}: {code.count(state)} State structs"
    decl = "".join(f'static GenRefBuffer {b}("{b}");  // undeclared by the export, see scripts/patch_export.py\n' for b in bufs)
    code = code.replace(state, decl + state)
open(dst, "w").write(f"// generated by scripts/patch_export.py from {src}: {k} noise site(s)"
                     + (f", buffer(s) {', '.join(bufs)}" if bufs else "") + "\n"
                     f"#define GEN_NOISE_SITES {k}\n" + code)
